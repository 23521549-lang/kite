export type ConnectLang = 'vi' | 'en'

export function connectStrings(lang: ConnectLang): Record<ConnectKey, string> {
  return lang === 'en' ? connectEn : connectVi
}

/** Current UI language, read from the same localStorage key Gói 0(b) specified. */
export function useConnectStrings(): Record<ConnectKey, string> {
  const [lang] = useState<ConnectLang>(() => (localStorage.getItem('kite-language') === 'en' ? 'en' : 'vi'))
  return connectStrings(lang)
}
